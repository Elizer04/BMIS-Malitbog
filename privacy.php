        <div class="highlight-box">
            <p><i class="fa-solid fa-shield-halved"></i> Barangay Malitbog values your privacy. All information collected through the E-Barangay Management Information System is handled in strict compliance with Republic Act No. 10173 (Data Privacy Act of 2012).</p>
